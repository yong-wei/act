// 获取节点的关联节点
export function getRelatedNodes(nodeId: string): string[] {
  const node = controlTheoryNodes.find((n) => n.id === nodeId);
  if (!node) return [];

  const related = new Set<string>();

  // 添加前置节点
  node.prerequisites.forEach((id) => related.add(id));

  // 添加相关主题
  node.relatedTopics.forEach((id) => related.add(id));

  // 添加通过边连接的节点
  controlTheoryEdges.forEach((edge) => {
    if (edge.source === nodeId) related.add(edge.target);
    if (edge.target === nodeId) related.add(edge.source);
  });

  return Array.from(related);
}
